import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "teck-cloud-dotnet-policy-"));
const report = { temporary, checks: [] };
const settings = [
  "global.json",
  "Directory.Build.props",
  "Directory.Packages.props",
  ".editorconfig",
  "stylecop.json",
  "nuget.config",
];
for (const file of settings)
  fs.copyFileSync(path.join(repository, file), path.join(temporary, file));
const project =
  '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><RootNamespace>Teck.Cloud.Verification</RootNamespace></PropertyGroup></Project>\n';
const clean = `namespace Teck.Cloud.Verification;

/// <summary>Exercises the shared build policy.</summary>
public static class Probe
{
    /// <summary>Adds two values.</summary>
    /// <param name="left">The first value.</param>
    /// <param name="right">The second value.</param>
    /// <returns>The sum.</returns>
    public static int Add(int left, int right) => left + right + GeneratedValues.Offset;
}
`;
const generated =
  "// <auto-generated/>\nnamespace Teck.Cloud.Verification;\ninternal static class GeneratedValues { internal const int Offset = 0; }\n";
const source = path.join(temporary, "src", "Probe");
const tests = path.join(temporary, "tests", "unit", "Probe");
for (const directory of [source, tests]) {
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, "Probe.csproj"), project);
  fs.writeFileSync(path.join(directory, "Probe.cs"), clean);
  fs.writeFileSync(path.join(directory, "GeneratedValues.g.cs"), generated);
}
function dotnet(args, label, expectedCode) {
  // Only these disposable generated projects may create their own lockfiles in CI.
  const fixtureArgs = args.includes("--locked-mode")
    ? args
    : [...args, "-p:RestoreLockedMode=false"];
  const run = spawnSync("dotnet", fixtureArgs, {
    cwd: temporary,
    encoding: "utf8",
    timeout: 180_000,
    maxBuffer: 10 * 1024 * 1024,
    env: { ...process.env, DOTNET_NOLOGO: "true" },
  });
  const output = (run.stdout ?? "") + (run.stderr ?? "");
  assert.ifError(run.error);
  assert.doesNotMatch(
    output,
    /(?:error|warning) (?:AD0001|CS8032|CS9057)\b/,
    "An analyzer failed to load or execute",
  );
  if (expectedCode) {
    assert.notEqual(run.status, 0, `${label} unexpectedly passed`);
    assert.match(output, new RegExp(`error ${expectedCode}\\b`), `${label}\n${output}`);
  } else {
    assert.equal(run.status, 0, `${label}\n${output}`);
    assert.doesNotMatch(output, /\bwarning [A-Z]+[0-9]+\b/, `${label} emitted a warning`);
  }
  report.checks.push({ label, expectedCode: expectedCode ?? null, passed: true });
  console.log(`PASS: ${label}`);
}
function build(directory, label, code, configuration = "Release") {
  dotnet(
    [
      "build",
      path.join(directory, "Probe.csproj"),
      "-c",
      configuration,
      "--no-restore",
      "--nologo",
      "-v",
      "minimal",
    ],
    label,
    code,
  );
}
const cases = [
  [
    "nullable warnings are errors",
    "CS8602",
    "public static int Length(string? value) => value.Length;",
  ],
  ["StyleCop documentation is enforced", "SA1600", "public static int Value() => 42;"],
  [
    "async blocking is rejected",
    "VSTHRD002",
    "public static int Wait(Task<int> task) => task.Result;",
  ],
  [
    "cancellation is forwarded",
    "CA2016",
    "public static Task DelayAsync(CancellationToken cancellationToken) => Task.Delay(1);",
  ],
  [
    "Sonar detects identical operands",
    "S1764",
    "public static int Subtract(int value) => value - value;",
  ],
  [
    "security analysis rejects weak hashing",
    "CA5351",
    "public static byte[] Hash(byte[] input) => System.Security.Cryptography.MD5.HashData(input);",
  ],
];
try {
  for (const directory of [source, tests])
    dotnet(
      ["restore", path.join(directory, "Probe.csproj"), "--nologo", "-v", "minimal"],
      `restore ${path.relative(temporary, directory)}`,
    );
  const sourceProject = path.join(source, "Probe.csproj");
  dotnet(
    ["restore", sourceProject, "--locked-mode"],
    "unchanged dependencies restore in locked mode",
  );
  fs.writeFileSync(
    sourceProject,
    project.replace(
      "</Project>",
      '<ItemGroup><PackageReference Include="ErrorOr" /></ItemGroup></Project>',
    ),
  );
  dotnet(
    ["restore", sourceProject, "--locked-mode"],
    "locked restore rejects dependency drift",
    "NU1004",
  );
  fs.writeFileSync(sourceProject, project);
  dotnet(
    ["restore", sourceProject, "--locked-mode"],
    "locked restore recovers after drift is reverted",
  );
  build(source, "clean source and generated code compile");
  build(tests, "clean test-directory project compiles", undefined, "Debug");
  for (const [label, diagnostic, method] of cases) {
    fs.writeFileSync(
      path.join(source, "Probe.cs"),
      "namespace Teck.Cloud.Verification;\n\n/// <summary>Exercises failure detection.</summary>\npublic static class Probe\n{\n    " +
        method +
        "\n}\n",
    );
    build(source, label, diagnostic);
  }
  fs.writeFileSync(
    path.join(tests, "Probe.cs"),
    "namespace Teck.Cloud.Verification;\npublic static class Probe { public static int Length(string? value) => value.Length; }\n",
  );
  build(tests, "test-directory warnings also fail Debug builds", "CS8602", "Debug");
  fs.writeFileSync(path.join(source, "Probe.cs"), clean);
  fs.writeFileSync(
    path.join(source, "GeneratedValues.g.cs"),
    generated.replace("= 0", '= "invalid"'),
  );
  build(source, "generated code still receives compiler checks", "CS0029");
  fs.writeFileSync(path.join(source, "GeneratedValues.g.cs"), generated);
  build(source, "clean build recovers after violations are fixed");
  const stack = path.join(temporary, "src", "Stack");
  fs.mkdirSync(stack, { recursive: true });
  const fixtures = JSON.parse(
    fs.readFileSync(path.join(repository, "tools/dotnet-policy/stack-fixtures.json"), "utf8"),
  );
  for (const [file, contents] of Object.entries(fixtures))
    fs.writeFileSync(path.join(stack, file), contents);
  dotnet(
    ["build", path.join(stack, "Stack.csproj"), "-c", "Release", "--nologo", "-v", "minimal"],
    "service stack and source generators compile together",
  );
} finally {
  fs.mkdirSync(path.join(repository, ".artifacts"), { recursive: true });
  fs.writeFileSync(
    path.join(repository, ".artifacts/dotnet-policy-verification.json"),
    `${JSON.stringify(report, null, 2)}\n`,
  );
  // Keep the isolated workspace for diagnosis; never delete a caller-owned path.
  console.log(`Verification workspace: ${temporary}`);
}
