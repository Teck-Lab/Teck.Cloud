import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const applications = {
  storefront: {
    directory: "src/apps/storefront",
    contract: "docs/contracts/commerce/v1/customer.openapi.yaml",
    output: "src/apps/storefront/src/server/commerce/api.generated.ts",
    title: "customer",
  },
  admin: {
    directory: "src/apps/admin",
    contract: "docs/contracts/commerce/v1/admin.openapi.yaml",
    output: "src/apps/admin/src/server/commerce/api.generated.ts",
    title: "admin",
  },
};

const banner = [
  "// biome-ignore-all format: generated by tools/generate-commerce-api.mjs",
  "// biome-ignore-all lint: generated by tools/generate-commerce-api.mjs",
  "",
].join("\n");

function parseArguments(argv) {
  let application = null;
  let check = false;

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--app") {
      application = argv[index + 1];
      index += 1;
    } else if (argument.startsWith("--app=")) {
      application = argument.slice("--app=".length);
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }

  if (application !== null && !Object.hasOwn(applications, application)) {
    throw new Error(`Unknown application: ${application}`);
  }

  return {
    check,
    applications: application === null ? Object.keys(applications) : [application],
  };
}

async function render({ contract, directory, title }) {
  // Resolve from the owning application so its pinned generator and TypeScript peer are used.
  const requireFromApplication = createRequire(
    path.join(repositoryRoot, directory, "package.json"),
  );
  const generator = await import(
    pathToFileURL(requireFromApplication.resolve("openapi-typescript")).href
  );
  const loaded = generator.default;
  const openapiTS = typeof loaded === "function" ? loaded : loaded?.default;
  const astToString = generator.astToString ?? loaded?.astToString;
  if (typeof openapiTS !== "function" || typeof astToString !== "function") {
    throw new Error(`Unable to load openapi-typescript from ${directory}.`);
  }

  const ast = await openapiTS(pathToFileURL(path.join(repositoryRoot, contract)));
  const header = [
    "/**",
    ` * This file was auto-generated by openapi-typescript from the ${title} commerce contract.`,
    " * Do not make direct changes to the file.",
    " * Run `bun run generate:commerce-api` after changing the contract instead.",
    " */",
    "",
  ].join("\n");

  return `${banner}${header}${astToString(ast)}\n`;
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  let failed = false;

  for (const name of options.applications) {
    const application = applications[name];
    const outputPath = path.join(repositoryRoot, application.output);
    const expected = await render(application);

    if (options.check) {
      let actual = null;
      try {
        actual = await readFile(outputPath, "utf8");
      } catch {
        console.error(`${application.output} is missing.`);
      }

      if (actual !== expected) {
        console.error(
          `${application.output} is out of date. Run \`bun run generate:commerce-api\`.`,
        );
        failed = true;
      }
      continue;
    }

    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, expected);
    console.log(`Generated ${application.output} from ${application.contract}.`);
  }

  if (failed) {
    process.exitCode = 1;
  }
}

try {
  await main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
